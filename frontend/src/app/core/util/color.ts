/** Helpers used to derive an accessible palette from the pharmacy's brand colors. */
export function isHexColor(value: string | null | undefined): value is string {
  return !!value && /^#[0-9a-fA-F]{6}$/.test(value);
}

export function relativeLuminance(hex: string): number {
  const channels = [1, 3, 5].map((offset) => parseInt(hex.slice(offset, offset + 2), 16) / 255);
  const [r, g, b] = channels.map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

export function contrastRatio(a: string, b: string): number {
  const [light, dark] = [relativeLuminance(a), relativeLuminance(b)].sort((x, y) => y - x);
  return (light + 0.05) / (dark + 0.05);
}

/** Text color (white or near-black) that keeps WCAG AA contrast on the given background. */
export function readableTextOn(background: string): string {
  return contrastRatio(background, '#FFFFFF') >= contrastRatio(background, '#111827')
    ? '#FFFFFF'
    : '#111827';
}
